-- Error taxonomy for objective answers. Severity: 1 minor slip, 2 costs marks, 3 blocks understanding or misreads the task.
-- DRAFT seed, pending review by an IELTS expert. Codes are stable identifiers stored inside answer specs and error
-- analysis rows, so renaming one later means a migration, not an edit.

CREATE TABLE error_types (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    code VARCHAR(60) NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_]*$'),
    name VARCHAR(255) NOT NULL,
    category VARCHAR(30) NOT NULL CHECK (category IN
        ('GRAMMAR', 'VOCABULARY', 'COHERENCE', 'TASK', 'READING_STRATEGY', 'LISTENING_STRATEGY', 'SPELLING_NUMBER')),
    severity SMALLINT NOT NULL CHECK (severity BETWEEN 1 AND 3),
    knowledge_point_id UUID REFERENCES knowledge_points(id),
    fix_hint TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_error_types_status ON error_types(status);

